const puppeteer = require('puppeteer-core');
const CHROME = 'C:/Program Files/Google/Chrome/Application/chrome.exe';
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
(async () => {
  const browser = await puppeteer.launch({ executablePath: CHROME, headless: 'new', args: ['--no-sandbox'] });
  const page = await browser.newPage();
  await page.setViewport({ width: 430, height: 900 });
  const errors = [];
  page.on('pageerror', (e) => errors.push('PAGEERROR: ' + e.message));
  page.on('console', (m) => { if (m.type() === 'error') errors.push('CONSOLE: ' + m.text().slice(0, 200)); });
  await page.goto('http://127.0.0.1:5173/me', { waitUntil: 'networkidle2', timeout: 30000 });
  await sleep(1500);
  const path = await page.evaluate(() => location.pathname);
  const rootHtml = await page.evaluate(() => document.getElementById('root').innerHTML.slice(0, 500));
  const allNames = await page.evaluate(() => Array.from(document.querySelectorAll('[data-name]')).map(e => e.getAttribute('data-name')).slice(0, 60));
  console.log('pathname:', path);
  console.log('root 前500字符:', rootHtml);
  console.log('data-name 列表(前60):', JSON.stringify(allNames, null, 0));
  console.log('JS错误:', errors.length ? errors.join('\n') : '无');
  await browser.close();
})();
